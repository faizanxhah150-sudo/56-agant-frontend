export function getToolBySlug(slug) {
  return TOOLS.find((t) => t.slug === slug);
}

export function getRelatedTools(tool, count = 3) {
  return TOOLS.filter((t) => t.category === tool.category && t.id !== tool.id).slice(0, count);
}
